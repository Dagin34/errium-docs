<script lang="ts">
	import { Search } from 'lucide-svelte';
	import { tick } from 'svelte';

	interface Result {
		url: string;
		title: string;
		excerpt: string;
	}

	interface Props {
		open: boolean;
		/** Focus returns here when the dialog closes. */
		trigger?: HTMLElement;
		onclose: () => void;
	}

	let { open = $bindable(), trigger, onclose }: Props = $props();

	let query = $state('');
	let results = $state<Result[]>([]);
	let activeIndex = $state(0);
	let searching = $state(false);
	let input = $state<HTMLInputElement>();
	let dialog = $state<HTMLElement>();

	let pagefind: { search: (q: string) => Promise<{ results: PagefindResult[] }> } | null = null;

	interface PagefindResult {
		data: () => Promise<{ url: string; meta?: { title?: string }; excerpt: string }>;
	}

	async function loadPagefind() {
		if (pagefind) return pagefind;
		try {
			// Pagefind is generated by the postbuild step and served from the
			// site root, so it doesn't exist while the bundler is running. The
			// specifier is built at runtime so the bundler can't try to resolve
			// it — a literal would fail the build even with @vite-ignore.
			const entry = '/pagefind/pagefind.js';
			pagefind = await import(/* @vite-ignore */ entry);
		} catch {
			pagefind = null;
		}
		return pagefind;
	}

	async function run(q: string) {
		if (!q.trim()) {
			results = [];
			return;
		}

		searching = true;
		const pf = await loadPagefind();

		if (!pf) {
			results = [];
			searching = false;
			return;
		}

		const search = await pf.search(q);
		const top = await Promise.all(search.results.slice(0, 8).map((r) => r.data()));

		results = top.map((d) => ({
			url: d.url.replace(/\.html$/, ''),
			title: d.meta?.title ?? 'Untitled',
			excerpt: d.excerpt
		}));
		activeIndex = 0;
		searching = false;
	}

	$effect(() => {
		run(query);
	});

	$effect(() => {
		if (!open) return;
		tick().then(() => input?.focus());
	});

	function close() {
		open = false;
		onclose();
		trigger?.focus();
	}

	function onKeydown(event: KeyboardEvent) {
		if (event.key === 'Escape') {
			event.preventDefault();
			close();
			return;
		}

		if (event.key === 'ArrowDown') {
			event.preventDefault();
			activeIndex = Math.min(activeIndex + 1, results.length - 1);
			return;
		}

		if (event.key === 'ArrowUp') {
			event.preventDefault();
			activeIndex = Math.max(activeIndex - 1, 0);
			return;
		}

		if (event.key === 'Enter' && results[activeIndex]) {
			event.preventDefault();
			window.location.href = results[activeIndex].url;
			return;
		}

		// Focus trap: the dialog is small enough to cycle explicitly.
		if (event.key === 'Tab') {
			const focusable = dialog?.querySelectorAll<HTMLElement>(
				'input, a[href], button:not([disabled])'
			);
			if (!focusable || focusable.length === 0) return;

			const first = focusable[0];
			const last = focusable[focusable.length - 1];

			if (event.shiftKey && document.activeElement === first) {
				event.preventDefault();
				last.focus();
			} else if (!event.shiftKey && document.activeElement === last) {
				event.preventDefault();
				first.focus();
			}
		}
	}
</script>

{#if open}
	<!-- svelte-ignore a11y_no_static_element_interactions -->
	<div
		class="fixed inset-0 z-50 flex items-start justify-center bg-bg/80 p-4 pt-24 backdrop-blur-sm"
		onclick={(e) => e.target === e.currentTarget && close()}
		onkeydown={onKeydown}
	>
		<div
			bind:this={dialog}
			role="dialog"
			aria-modal="true"
			aria-label="Search documentation"
			class="flex max-h-full w-full max-w-content flex-col overflow-hidden rounded-lg border bg-bg-elevated"
		>
			<div class="flex items-center gap-3 border-b px-4">
				<Search size={16} aria-hidden="true" class="shrink-0 text-fg-muted" />
				<input
					bind:this={input}
					bind:value={query}
					type="search"
					placeholder="Search the documentation"
					aria-label="Search the documentation"
					class="w-full bg-transparent py-4 text-body text-fg placeholder:text-fg-muted focus-visible:outline-none"
				/>
			</div>

			<div class="overflow-y-auto">
				{#if results.length > 0}
					<ul>
						{#each results as result, i (result.url)}
							<li>
								<a
									href={result.url}
									onmouseenter={() => (activeIndex = i)}
									class="block border-l px-4 py-3 transition-colors duration-150 ease-out focus-visible:outline-2 focus-visible:outline-offset-2 focus-visible:outline-fg
										{i === activeIndex ? 'border-fg bg-bg-subtle' : 'border-transparent'}"
								>
									<span class="block text-nav text-fg">{result.title}</span>
									<span class="mt-1 block text-nav text-fg-muted">{@html result.excerpt}</span>
								</a>
							</li>
						{/each}
					</ul>
				{:else if query.trim() && !searching}
					<!-- An empty state that still offers a way forward. -->
					<div class="px-4 py-8">
						<p class="text-nav text-fg">No matches for "{query}".</p>
						<p class="mt-2 text-nav text-fg-muted">
							Try <a href="/docs" class="underline underline-offset-4">Introduction</a> or
							<a href="/docs/quickstart" class="underline underline-offset-4">Quickstart</a>.
						</p>
					</div>
				{:else if !query.trim()}
					<p class="px-4 py-8 text-nav text-fg-muted">
						Search across every page. Try <code class="font-mono">classifier</code>,
						<code class="font-mono">debug</code>, or <code class="font-mono">422</code>.
					</p>
				{/if}
			</div>
		</div>
	</div>
{/if}
